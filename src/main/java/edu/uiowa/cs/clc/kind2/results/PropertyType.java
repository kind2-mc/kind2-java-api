package edu.uiowa.cs.clc.kind2.results;

/**
 * Enum for property types.
 */
public enum PropertyType
{
  /**
   * An assumption stated in a contract.
   */
  assumption("Assumption"),
  /**
   * A guarantee stated in a contract.
   */
  guarantee("Guarantee"),
  /**
   * An ensure clause of a contract mode.
   */
  ensure("Ensure"),
  /**
   * A property stated with a check annotation in the program.
   */
  annotation("PropAnnot"),
  /**
   * The check that at least one mode of a contract is active.
   */
  oneModeActive("OneModeActive"),
  /**
   * A property generated by Kind 2 rather than stated by the user.
   */
  generated("Generated"),
  /**
   * The check that a property is not vacuously true.
   */
  nonVacuityCheck("NonVacuityCheck"),
  /**
   * A termination check.
   */
  termination("Termination");

  private final String value;

  PropertyType(String value)
  {
    this.value = value;
  }

  /**
   * Returns the property type denoted by the given Kind 2 property type name.
   *
   * @param propertyType the Kind 2 property type name
   * @return the corresponding property type
   * @throws UnsupportedOperationException if the name is not recognised
   */
  public static PropertyType getPropertyType(String propertyType)
  {
    switch (propertyType)
    {
      case "Assumption":
      case "assumption":
        return assumption;
      case "Guarantee":
      case "guarantee":
        return guarantee;
      case "Ensure":
      case "ensure":
        return ensure;
      case "PropAnnot":
      case "propAnnot":
        return annotation;
      case "OneModeActive":
      case "oneModeActive":
        return oneModeActive;
      case "Generated":
      case "generated":
        return generated;
      case "NonVacuityCheck":
      case "nonVacuityCheck":
        return nonVacuityCheck;
      case "Termination":
      case "termination":
        return termination;
      default:
        throw new UnsupportedOperationException("Property type " + propertyType + " is not supported");
    }
  }

  @Override
  public String toString()
  {
    return this.value;
  }
}
